//! Native comparison harness: fixed workloads, an independent occurrence model,
//! and a shared requested-row scan loop.
//!
//! Product code is untouched. The arms reuse `lara_graph::traits::{DynamicCsr,
//! RemovableCsr}` directly; petgraph is wrapped only so that a `(src,dst)`-driven
//! removal can be expressed (its lookup cost is part of the measured update
//! phase, not hidden behind a precomputed edge id).

use crate::{
    DgapAdapter, LaraAdapter, LaraConfig, StaticCsr, coo_power_law_stream, coo_uniform_stream,
};
use lara_graph::traits::{DynamicCsr, RemovableCsr};
use petgraph::{Directed, Graph, graph::NodeIndex};

