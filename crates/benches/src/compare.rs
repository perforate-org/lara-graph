/// Arrival-order edge stream. The hub fixture is source 1, destinations 0..m in order.
pub fn stream(w: &Workload) -> Vec<(u32, u32)> {
    if w.hub {
        (0..w.m as u32).map(|t| (1u32, t)).collect()
    } else if w.uniform {
        coo_uniform_stream(w.n, w.m, w.seed)
    } else {
        coo_power_law_stream(w.n, w.m, w.seed, w.beta)
    }
}

/// Update occurrence count `k = min(4096, m/16)` (zero when m < 16).
pub fn update_k(m: u64) -> usize {
    (m / 16).min(4096) as usize
}

/// Fixed update pairs at original stream indices `floor(i*m/k)`; empty when k == 0.
pub fn update_pairs(stream: &[(u32, u32)], k: usize) -> Vec<(u32, u32)> {
    let m = stream.len();
    if k == 0 || m == 0 {
        return Vec::new();
    }
    (0..k).map(|i| stream[i * m / k]).collect()
}

/// Shared update application used by both the timed and smoke paths.
pub fn apply_updates<G: RemovableCsr>(g: &mut G, pairs: &[(u32, u32)]) {
    for &(src, dst) in pairs {
        assert!(g.remove_edge(src, dst), "update delete must succeed");
        g.insert_edge(src, dst);
    }
}

/// Independent occurrence model: per-source multiset of destinations.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Model {
    pub rows: Vec<Vec<u32>>,
    pub edges: u64,
    pub requested_nodes: u32,
}

pub fn model_for(stream: &[(u32, u32)], n: u32) -> Model {
    let mut rows = vec![Vec::new(); n as usize];
    for &(s, d) in stream {
        rows[s as usize].push(d);
    }
    Model {
        rows,
        edges: stream.len() as u64,
        requested_nodes: n,
    }
}

impl Model {
    pub fn remove(&mut self, s: u32, d: u32) -> bool {
        let row = &mut self.rows[s as usize];
        match row.iter().position(|&x| x == d) {
            Some(i) => {
                row.remove(i);
                self.edges -= 1;
                true
            }
            None => false,
        }
    }
    pub fn insert(&mut self, s: u32, d: u32) {
        self.rows[s as usize].push(d);
        self.edges += 1;
    }
}

/// Builds the bench-local petgraph arm with all vertices present up front.
pub fn pg_arm(n: u32, prealloc_edges: u64) -> PgArm {
    let mut g: Graph<(), (), Directed> = Graph::with_capacity(n as usize, prealloc_edges as usize);
    for _ in 0..n {
        g.add_node(());
    }
    PgArm { g }
}

/// Bench-local petgraph adapter. `prealloc_edges` is 0 for growing and `m` for
/// the preallocated arm; vertices are always created up front.
pub struct PgArm {
    g: Graph<(), (), Directed>,
}

impl PgArm {
    pub fn capacity(&self) -> (usize, usize) {
        self.g.capacity()
    }
    pub fn graph(&self) -> &Graph<(), (), Directed> {
        &self.g
    }
}

impl DynamicCsr for PgArm {
    fn num_nodes(&self) -> u64 {
        self.g.node_count() as u64
    }
    fn num_edges(&self) -> u64 {
        self.g.edge_count() as u64
    }
    fn out_degree(&self, v: u32) -> u64 {
        self.g.neighbors(NodeIndex::new(v as usize)).count() as u64
    }
    fn insert_edge(&mut self, src: u32, dst: u32) {
        self.g.add_edge(
            NodeIndex::new(src as usize),
            NodeIndex::new(dst as usize),
            (),
        );
    }
    fn for_each_neighbor<F: FnMut(u32)>(&self, v: u32, mut f: F) {
        for nb in self.g.neighbors(NodeIndex::new(v as usize)) {
            f(nb.index() as u32);
        }
    }
    fn scan_all<F: FnMut(u32)>(&self, mut f: F) {
        for v in 0..self.g.node_count() as u32 {
            self.for_each_neighbor(v, &mut f);
        }
    }
}

impl RemovableCsr for PgArm {
    fn remove_edge(&mut self, src: u32, dst: u32) -> bool {
        // The (src,dst) lookup is part of the update cost; no precomputed edge id.
        match self
            .g
            .find_edge(NodeIndex::new(src as usize), NodeIndex::new(dst as usize))
        {
            Some(e) => {
                self.g.remove_edge(e);
                true
            }
            None => false,
        }
    }
}

/// Padded-row expectations for the node-count oracle.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Nodes {
    /// num_nodes == requested n (petgraph, static CSR).
    Exact,
    /// num_nodes >= requested n padding allowed; padded rows must be empty (LARA, DGAP).
    Padded,
}

/// Reads every requested row into a multiset-preserving vector.
pub fn rows_of<G: DynamicCsr>(g: &G, n: u32) -> Vec<Vec<u32>> {
    (0..n)
        .map(|v| {
            let mut r = Vec::new();
            g.for_each_neighbor(v, |x| r.push(x));
            r
        })
        .collect()
}

/// Row multiset, per-row out_degree, total edge count and node-count oracle.
pub fn check_rows<G: DynamicCsr>(g: &G, model: &Model, nodes: Nodes, tag: &str) {
    assert_eq!(g.num_edges(), model.edges, "{tag}: total edge count");
    let actual = g.num_nodes();
    match nodes {
        Nodes::Exact => assert_eq!(actual, model.requested_nodes as u64, "{tag}: num_nodes"),
        Nodes::Padded => {
            assert!(
                actual >= model.requested_nodes as u64,
                "{tag}: num_nodes >= n"
            );
            for v in model.requested_nodes..actual as u32 {
                assert_eq!(g.out_degree(v), 0, "{tag}: padded row {v} must be empty");
            }
        }
    }
    let got = rows_of(g, model.requested_nodes);
    for (v, row) in got.iter().enumerate() {
        assert_eq!(
            g.out_degree(v as u32) as usize,
            model.rows[v].len(),
            "{tag}: out_degree {v}"
        );
        let mut a = row.clone();
        let mut b = model.rows[v].clone();
        a.sort_unstable();
        b.sort_unstable();
        assert_eq!(a, b, "{tag}: row {v} multiset");
    }
}

/// LARA check: oracle plus the existing owner invariant, outside timing.
pub fn check_lara(g: &LaraAdapter, model: &Model, tag: &str) {
    check_rows(g, model, Nodes::Padded, tag);
    g.verify();
}

/// DGAP check: oracle plus the existing owner invariant, outside timing.
pub fn check_dgap(g: &DgapAdapter, model: &Model, tag: &str) {
    check_rows(g, model, Nodes::Padded, tag);
    g.verify();
}

/// Shared requested-row checksum.
pub fn scan_sum<G: DynamicCsr>(g: &G, n: u32) -> u64 {
    let mut sum = 0u64;
    for v in 0..n {
        g.for_each_neighbor(v, |x| sum = sum.wrapping_add(x as u64));
    }
    sum
}

/// Deterministic FNV-1a fingerprint of an arrival stream (input identity for the
/// evidence CSV and the freeze file).
pub fn stream_fingerprint(stream: &[(u32, u32)]) -> u64 {
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for &(a, b) in stream {
        for x in [a, b] {
            for byte in x.to_le_bytes() {
                h ^= byte as u64;
                h = h.wrapping_mul(0x0000_0100_0000_01b3);
            }
        }
    }
    h
}

/// One time case: workload, arm and phase.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct TimeCase {
    pub workload: &'static str,
    pub arm: &'static str,
    pub phase: &'static str,
}

impl TimeCase {
    /// Exact Criterion id used by the bench target for this case.
    pub fn criterion_id(&self) -> String {
        format!("time/{}/{}/{}", self.arm, self.phase, self.workload)
    }
}

