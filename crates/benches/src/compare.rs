/// Inserts a whole arrival stream through the shared trait path (used by both
/// the timed `I` body and the smoke path).
pub fn insert_stream<G: DynamicCsr>(g: &mut G, stream: &[(u32, u32)]) {
    for &(src, dst) in stream {
        g.insert_edge(src, dst);
    }
}

/// Runtime arm holder for the smoke/memory paths (the timed phases stay
/// monomorphized over `DynamicCsr`). Inline variants are intentional: the timed
/// graphs live on the stack, so boxing only here would make the memory probe's
/// graph-object accounting differ from the timed path.
#[allow(clippy::large_enum_variant)]
pub enum AnyGraph {
    L(LaraAdapter),
    PG(PgArm),
    PGP(PgArm),
    D(DgapAdapter),
    CSR(StaticCsr),
}

impl AnyGraph {
    pub fn new(arm: &str, w: &Workload, stream: &[(u32, u32)], prealloc_edges: u64) -> Self {
        match arm {
            "L" => AnyGraph::L(LaraAdapter::new(w.n, LaraConfig::default()).unwrap()),
            "PG" => AnyGraph::PG(pg_arm(w.n, prealloc_edges)),
            "PGP" => AnyGraph::PGP(pg_arm(w.n, prealloc_edges)),
            "D" => AnyGraph::D(DgapAdapter::new(w.n).unwrap()),
            "CSR" => AnyGraph::CSR(StaticCsr::new(w.n, stream)),
            other => panic!("unknown arm {other}"),
        }
    }
    pub fn insert(&mut self, s: u32, d: u32) {
        match self {
            AnyGraph::L(a) => a.insert_edge(s, d),
            AnyGraph::PG(a) | AnyGraph::PGP(a) => a.insert_edge(s, d),
            AnyGraph::D(a) => a.insert_edge(s, d),
            AnyGraph::CSR(_) => panic!("read-only"),
        }
    }
    pub fn insert_all(&mut self, stream: &[(u32, u32)]) {
        match self {
            AnyGraph::L(a) => insert_stream(a, stream),
            AnyGraph::PG(a) | AnyGraph::PGP(a) => insert_stream(a, stream),
            AnyGraph::D(a) => insert_stream(a, stream),
            AnyGraph::CSR(_) => panic!("read-only"),
        }
    }
    pub fn remove(&mut self, s: u32, d: u32) -> bool {
        match self {
            AnyGraph::L(a) => a.remove_edge(s, d),
            AnyGraph::PG(a) | AnyGraph::PGP(a) => a.remove_edge(s, d),
            AnyGraph::D(a) => a.remove_edge(s, d),
            AnyGraph::CSR(_) => panic!("read-only"),
        }
    }
    pub fn apply(&mut self, pairs: &[(u32, u32)]) {
        match self {
            AnyGraph::L(a) => apply_updates(a, pairs),
            AnyGraph::PG(a) | AnyGraph::PGP(a) => apply_updates(a, pairs),
            AnyGraph::D(a) => apply_updates(a, pairs),
            AnyGraph::CSR(_) => panic!("read-only"),
        }
    }
    pub fn settle_lara(&mut self) {
        if let AnyGraph::L(a) = self {
            a.settle();
        } else {
            panic!("only the LARA arm has settle");
        }
    }
    pub fn scan_sum(&self, n: u32) -> u64 {
        match self {
            AnyGraph::L(a) => scan_sum(a, n),
            AnyGraph::PG(a) | AnyGraph::PGP(a) => scan_sum(a, n),
            AnyGraph::D(a) => scan_sum(a, n),
            AnyGraph::CSR(a) => scan_sum(a, n),
        }
    }
    pub fn check(&self, m: &Model, tag: &str) {
        match self {
            AnyGraph::L(a) => check_lara(a, m, tag),
            AnyGraph::PG(a) | AnyGraph::PGP(a) => check_rows(a, m, Nodes::Exact, tag),
            AnyGraph::D(a) => check_dgap(a, m, tag),
            AnyGraph::CSR(a) => check_rows(a, m, Nodes::Exact, tag),
        }
    }
    pub fn num_edges(&self) -> u64 {
        match self {
            AnyGraph::L(a) => a.num_edges(),
            AnyGraph::PG(a) | AnyGraph::PGP(a) => a.num_edges(),
            AnyGraph::D(a) => a.num_edges(),
            AnyGraph::CSR(a) => a.num_edges(),
        }
    }
    pub fn num_nodes(&self) -> u64 {
        match self {
            AnyGraph::L(a) => a.num_nodes(),
            AnyGraph::PG(a) | AnyGraph::PGP(a) => a.num_nodes(),
            AnyGraph::D(a) => a.num_nodes(),
            AnyGraph::CSR(a) => a.num_nodes(),
        }
    }
    pub fn pg_capacity(&self) -> Option<(usize, usize)> {
        match self {
            AnyGraph::PG(a) | AnyGraph::PGP(a) => Some(a.capacity()),
            _ => None,
        }
    }
    /// Actual graph value size for this concrete arm (not the enum max).
    pub fn object_bytes(&self) -> usize {
        match self {
            AnyGraph::L(a) => std::mem::size_of_val(a),
            AnyGraph::PG(a) | AnyGraph::PGP(a) => std::mem::size_of_val(a),
            AnyGraph::D(a) => std::mem::size_of_val(a),
            AnyGraph::CSR(a) => std::mem::size_of_val(a),
        }
    }
}

/// Builds an arm, inserts `stream` through the shared path, then optionally
/// applies `pairs` (shared path) and settles. CSR is read-only.
pub fn build_any(
    arm: &str,
    w: &Workload,
    stream: &[(u32, u32)],
    apply: &[(u32, u32)],
    settle: bool,
) -> AnyGraph {
    assert!(arm != "CSR", "CSR is read-only; construct it directly");
    let pre = if arm == "PGP" { w.m } else { 0 };
    let mut a = AnyGraph::new(arm, w, stream, pre);
    a.insert_all(stream);
    a.apply(apply);
    if settle {
        a.settle_lara();
    }
    a
}

#[cfg(test)]
fn rows_of_ref(a: &AnyGraph, n: u32) -> Vec<Vec<u32>> {
    (0..n)
        .map(|v| {
            let mut r = Vec::new();
            match a {
                AnyGraph::L(x) => x.for_each_neighbor(v, |t| r.push(t)),
                AnyGraph::PG(x) | AnyGraph::PGP(x) => x.for_each_neighbor(v, |t| r.push(t)),
                AnyGraph::D(x) => x.for_each_neighbor(v, |t| r.push(t)),
                AnyGraph::CSR(x) => x.for_each_neighbor(v, |t| r.push(t)),
            }
            r
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn graph(arm: &str) -> AnyGraph {
        let w = Workload {
            name: "tiny",
            n: 8,
            m: 8,
            uniform: true,
            beta: 0.0,
            seed: 1,
            hub: false,
        };
        AnyGraph::new(arm, &w, &[], 0)
    }

    #[test]
    fn lara_remove_miss_returns_false() {
        let mut a = graph("L");
        a.insert(0, 1);
        assert!(!a.remove(0, 2), "absent edge must report false");
        assert!(a.remove(0, 1));
    }

    #[test]
    fn lara_duplicate_single_delete_before_and_after_reinsert() {
        let mut a = graph("L");
        a.insert(0, 1);
        a.insert(0, 1);
        assert!(a.remove(0, 1), "one duplicate removed");
        assert_eq!(
            rows_of_ref(&a, 8)[0],
            vec![1],
            "one occurrence remains before reinsert"
        );
        a.insert(0, 1);
        let mut row = rows_of_ref(&a, 8)[0].clone();
        row.sort_unstable();
        assert_eq!(row, vec![1, 1], "two occurrences after reinsert");
    }

    #[test]
    fn lara_self_loop_roundtrip() {
        let mut a = graph("L");
        a.insert(3, 3);
        assert!(a.remove(3, 3));
        assert!(rows_of_ref(&a, 8)[3].is_empty());
    }

    #[test]
    fn pg_lookup_delete_miss_and_duplicate() {
        let mut a = graph("PG");
        a.insert(0, 1);
        a.insert(0, 1);
        assert!(!a.remove(0, 2));
        assert!(a.remove(0, 1));
        assert_eq!(rows_of_ref(&a, 8)[0], vec![1]);
        a.insert(0, 1);
        assert_eq!(rows_of_ref(&a, 8)[0].len(), 2);
        a.insert(3, 3);
        assert!(a.remove(3, 3));
    }

    #[test]
    fn static_csr_is_read_only_and_exact_nodes() {
        let s = vec![(0u32, 1u32), (0, 2), (3, 3)];
        let model = model_for(&s, 8);
        let csr = StaticCsr::new(8, &s);
        check_rows(&csr, &model, Nodes::Exact, "csr");
        assert_eq!(scan_sum(&csr, 8), 1 + 2 + 3);
    }

    #[test]
    fn update_contract() {
        let s: Vec<(u32, u32)> = (0..16u32).map(|i| (i, 0)).collect();
        assert_eq!(update_pairs(&s, 4), vec![(0, 0), (4, 0), (8, 0), (12, 0)]);
        assert_eq!(update_k(40_000), 2500);
        assert_eq!(update_k(400_000), 4096);
        assert_eq!(update_k(8), 0);
        assert!(update_pairs(&[], 0).is_empty());
        assert!(update_pairs(&s, 0).is_empty());
    }

    #[test]
    fn frozen_case_tables_are_unique() {
        let tc = time_cases();
        assert_eq!(tc.len(), 85);
        let ids: std::collections::BTreeSet<String> = tc.iter().map(|c| c.criterion_id()).collect();
        assert_eq!(ids.len(), 85, "time case ids must be unique");
        assert_eq!(memory_cases().len(), 40);
    }
}
